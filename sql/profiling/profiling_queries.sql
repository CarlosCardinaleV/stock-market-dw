-- DESCRIPTIVE FIELDS: domain, absolute distribution, and %
-- SYMBOL (STG_DAILY_PRICES)
SELECT
    SYMBOL,
    COUNT(*) AS ABS_FREQ,
    ROUND(RATIO_TO_REPORT(COUNT(*)) OVER () * 100, 2) AS FREQ_PCT
FROM
    STG_DAILY_PRICES
GROUP BY
    SYMBOL
ORDER BY
    ABS_FREQ DESC;

-- SECTOR (STG_COMPANY_OVERVIEW)
SELECT
    SECTOR,
    COUNT(*) AS ABS_FREQ,
    ROUND(RATIO_TO_REPORT(COUNT(*)) OVER () * 100, 2) AS FREQ_PCT
FROM
    STG_COMPANY_OVERVIEW
GROUP BY
    SECTOR
ORDER BY
    ABS_FREQ DESC;

-- INDUSTRY, EXCHANGE, COUNTRY: same template
SELECT
    EXCHANGE,
