-- Integridad referencial implícita entre fuentes:
-- símbolos con precios pero sin metadatos de empresa (debe ser 0)
SELECT
    DISTINCT p.SYMBOL
FROM
    STG_DAILY_PRICES p
WHERE
    NOT EXISTS (SELECT 1 FROM STG_COMPANY_OVERVIEW o
        WHERE o.SYMBOL = p.SYMBOL);

-- Precios o volúmenes no positivos (esperado: 0)
SELECT
    COUNT(*) AS VALORES_NO_POSITIVOS
FROM
    STG_DAILY_PRICES
WHERE
    OPEN_PRICE <= 0
    OR HIGH_PRICE <= 0
    OR LOW_PRICE <= 0
    OR  CLOSE_PRICE <= 0
    OR VOLUME < 0;

-- Huecos de calendario: días hábiles sin cotización por símbolo
SELECT
    SYMBOL,
    COUNT(*) AS DIAS, 
    MAX(TRADE_DATE) - MIN(TRADE_DATE) AS RANGO_DIAS_CALENDARIO,
    ROUND(COUNT(*) / ((MAX(TRADE_DATE) - MIN(TRADE_DATE)) * 5/7), 4) AS COBERTURA_APROX
FROM
    STG_DAILY_PRICES
GROUP BY
    SYMBOL
ORDER BY
    COBERTURA_APROX;

-- Para jerarquias de analisis
-- Jerarquía temporal: cardinalidad por nivel
SELECT
    COUNT(DISTINCT EXTRACT(YEAR FROM TRADE_DATE)) AS ANIOS,
    COUNT(DISTINCT TO_CHAR(TRADE_DATE,'YYYY-Q')) AS TRIMESTRES,
    COUNT(DISTINCT TO_CHAR(TRADE_DATE,'YYYY-MM')) AS MESES,
    COUNT(DISTINCT TRADE_DATE) AS DIAS
FROM
    STG_DAILY_PRICES;

-- Jerarquía organizacional: Sector > Industria > Compañía
SELECT
    SECTOR,
    INDUSTRY,
    COUNT(*) AS COMPANIAS
FROM
    STG_COMPANY_OVERVIEW
GROUP BY
    ROLLUP (SECTOR, INDUSTRY)
ORDER BY
    SECTOR,
    INDUSTRY
;


