-- SECTION C: OLAP EXTENSIONS (ROLLUP, CUBE, NTILE)
-- ============================================================

-- C.1 Total trading volume with hierarchical ROLLUP
-- Sector > Symbol > Year — subtotals at each level
SELECT NVL(c.SECTOR, '(TOTAL)') AS SECTOR,
       NVL(c.SYMBOL, '(SECTOR)') AS SYMBOL,
       NVL(TO_CHAR(d.YEAR_NUM), '(YEARS)') AS YEAR,
       ROUND(SUM(f.VOLUME) / 1e6, 2) AS VOLUME_MILLIONS,
       ROUND(SUM(f.TRADED_VALUE) / 1e9, 4) AS TRADED_VALUE_BILLIONS
FROM FACT_DAILY_QUOTE f
JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
GROUP BY ROLLUP (c.SECTOR, c.SYMBOL, d.YEAR_NUM)
ORDER BY c.SECTOR, c.SYMBOL, d.YEAR_NUM;

-- C.2 Sector × Year CUBE: complete cross-analysis
-- Generates all possible combinations (sector, year, and total)
SELECT NVL(c.SECTOR, '(ALL)') AS SECTOR,
       NVL(TO_CHAR(d.YEAR_NUM), '(ALL)') AS YEAR,
       ROUND(AVG(f.CLOSE_PRICE), 2) AS AVG_PRICE,
       ROUND(AVG(f.DAILY_RETURN_PCT), 4) AS AVG_RETURN,
       ROUND(AVG(f.VOLATILITY_20), 4) AS AVG_VOLATILITY
FROM FACT_DAILY_QUOTE f
JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
WHERE f.DAILY_RETURN_PCT IS NOT NULL
GROUP BY CUBE (c.SECTOR, d.YEAR_NUM)
ORDER BY c.SECTOR, d.YEAR_NUM;

-- C.3 Stock classification by annual-return quartile
-- NTILE(4) within each year: Q1=worst, Q4=best
WITH ANNUAL AS (
    SELECT c.SYMBOL, c.SECTOR, d.YEAR_NUM,
           ROUND(AVG(f.DAILY_RETURN_PCT), 4) AS AVG_RETURN
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
    WHERE f.DAILY_RETURN_PCT IS NOT NULL
    GROUP BY c.SYMBOL, c.SECTOR, d.YEAR_NUM
)
SELECT SYMBOL, SECTOR, YEAR_NUM, AVG_RETURN,
       NTILE(4) OVER (PARTITION BY YEAR_NUM ORDER BY AVG_RETURN) AS QUARTILE,
       PERCENT_RANK() OVER (PARTITION BY YEAR_NUM ORDER BY AVG_RETURN) AS PERCENTILE,
       CUME_DIST() OVER (PARTITION BY YEAR_NUM ORDER BY AVG_RETURN) AS CUMULATIVE_DISTRIBUTION
FROM ANNUAL
ORDER BY YEAR_NUM, QUARTILE DESC, AVG_RETURN DESC;

-- C.4 Company ranking by total return in each sector
-- DENSE_RANK with RATIO_TO_REPORT for volume share
WITH TOTALS AS (
    SELECT c.SYMBOL, c.COMPANY_NAME, c.SECTOR,
           ROUND(SUM(f.TRADED_VALUE) / 1e9, 4) AS TOTAL_VALUE_BILLIONS,
           ROUND(AVG(f.DAILY_RETURN_PCT), 4) AS AVG_DAILY_RETURN,
           ROUND((LAST_VALUE(f.CLOSE_PRICE) OVER (
               PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
               ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING)
               / FIRST_VALUE(f.CLOSE_PRICE) OVER (
               PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
               ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING)
               - 1) * 100, 2) AS TOTAL_RETURN_PCT
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    GROUP BY c.SYMBOL, c.COMPANY_NAME, c.SECTOR,
             f.COMPANY_KEY, f.CLOSE_PRICE, f.DATE_KEY
),
GROUPED AS (
    SELECT SYMBOL, COMPANY_NAME, SECTOR,
           MAX(TOTAL_VALUE_BILLIONS) AS TOTAL_VALUE_BILLIONS,
           MAX(AVG_DAILY_RETURN) AS AVG_DAILY_RETURN,
           MAX(TOTAL_RETURN_PCT) AS TOTAL_RETURN_PCT
    FROM TOTALS
    GROUP BY SYMBOL, COMPANY_NAME, SECTOR
)
SELECT SYMBOL, COMPANY_NAME, SECTOR, TOTAL_VALUE_BILLIONS, TOTAL_RETURN_PCT,
       DENSE_RANK() OVER (
           PARTITION BY SECTOR ORDER BY TOTAL_RETURN_PCT DESC
       ) AS SECTOR_RANK,
       ROUND(RATIO_TO_REPORT(TOTAL_VALUE_BILLIONS) OVER (
           PARTITION BY SECTOR
       ) * 100, 2) AS VOLUME_SHARE_PCT
FROM GROUPED
ORDER BY SECTOR, SECTOR_RANK;

