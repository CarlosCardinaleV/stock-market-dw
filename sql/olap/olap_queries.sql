-- SECTION D: ADVANCED WINDOW FUNCTIONS
-- ============================================================

-- D.1 Maximum drawdown per symbol
-- Maximum percentage decline from historical peak to trough
WITH PEAKS AS (
    SELECT c.SYMBOL, d.FULL_DATE, f.CLOSE_PRICE,
           MAX(f.CLOSE_PRICE) OVER (
               PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
               ROWS UNBOUNDED PRECEDING
           ) AS HISTORICAL_PEAK
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
),
DRAWDOWNS AS (
    SELECT SYMBOL, FULL_DATE, CLOSE_PRICE, HISTORICAL_PEAK,
           ROUND((CLOSE_PRICE / HISTORICAL_PEAK - 1) * 100, 2) AS DRAWDOWN_PCT
    FROM PEAKS
)
SELECT SYMBOL, MIN(DRAWDOWN_PCT) AS MAX_DRAWDOWN_PCT,
       FULL_DATE AS MAX_DRAWDOWN_DATE
FROM DRAWDOWNS
GROUP BY SYMBOL, FULL_DATE
HAVING DRAWDOWN_PCT = (
    SELECT MIN(d2.DRAWDOWN_PCT)
    FROM DRAWDOWNS d2
    WHERE d2.SYMBOL = DRAWDOWNS.SYMBOL
)
ORDER BY MAX_DRAWDOWN_PCT;

-- D.2 Return correlation between stock pairs
-- Uses the CORR() function with a self-join
-- (requires access to two rows from the same day → self-join)
WITH RETURNS AS (
    SELECT c.SYMBOL, f.DATE_KEY, f.DAILY_RETURN_PCT
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    WHERE f.DAILY_RETURN_PCT IS NOT NULL
)
SELECT a.SYMBOL AS SYMBOL_A, b.SYMBOL AS SYMBOL_B,
       COUNT(*) AS COMMON_DAYS,
       ROUND(CORR(a.DAILY_RETURN_PCT, b.DAILY_RETURN_PCT), 4) AS CORRELATION
FROM RETURNS a
JOIN RETURNS b ON b.DATE_KEY = a.DATE_KEY AND b.SYMBOL > a.SYMBOL
GROUP BY a.SYMBOL, b.SYMBOL
HAVING COUNT(*) >= 100
ORDER BY ABS(CORR(a.DAILY_RETURN_PCT, b.DAILY_RETURN_PCT)) DESC;

-- D.3 Sector momentum: volume-weighted average return
-- in a rolling 60-business-day window
-- Identifies which sectors lead the market at each point in time
WITH BASE AS (
    SELECT c.SECTOR, d.FULL_DATE, f.DATE_KEY,
           SUM(f.DAILY_RETURN_PCT * f.VOLUME) OVER (
               PARTITION BY c.SECTOR ORDER BY f.DATE_KEY
               ROWS BETWEEN 59 PRECEDING AND CURRENT ROW
           ) AS WEIGHTED_RETURN_60D,
           SUM(f.VOLUME) OVER (
               PARTITION BY c.SECTOR ORDER BY f.DATE_KEY
               ROWS BETWEEN 59 PRECEDING AND CURRENT ROW
           ) AS VOLUME_60D,
           COUNT(*) OVER (
               PARTITION BY c.SECTOR ORDER BY f.DATE_KEY
               ROWS BETWEEN 59 PRECEDING AND CURRENT ROW
           ) AS WINDOW_ROWS
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
    WHERE f.DAILY_RETURN_PCT IS NOT NULL
)
SELECT SECTOR, FULL_DATE,
       ROUND(WEIGHTED_RETURN_60D / NULLIF(VOLUME_60D, 0), 6) AS MOMENTUM_60D,
       RANK() OVER (
           PARTITION BY DATE_KEY
           ORDER BY WEIGHTED_RETURN_60D / NULLIF(VOLUME_60D, 0) DESC
       ) AS SECTOR_RANK
FROM BASE
WHERE WINDOW_ROWS >= 60
ORDER BY SECTOR, FULL_DATE;

-- D.4 Significant bullish gap days (gap-up > 2%)
-- Today's OPEN_PRICE > yesterday's CLOSE_PRICE by more than 2%
-- A "gap" is a price jump between the previous close
-- and the following day's open — a signal of relevant news
SELECT c.SYMBOL, d.FULL_DATE AS GAP_DATE,
       f.OPEN_PRICE AS TODAY_OPEN,
       LAG(f.CLOSE_PRICE) OVER (
           PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
       ) AS YESTERDAY_CLOSE,
       ROUND((f.OPEN_PRICE / NULLIF(LAG(f.CLOSE_PRICE) OVER (
           PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
       ), 0) - 1) * 100, 2) AS GAP_PCT
FROM FACT_DAILY_QUOTE f
JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
WHERE (f.OPEN_PRICE / NULLIF(LAG(f.CLOSE_PRICE) OVER (
    PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
), 0) - 1) * 100 > 2
ORDER BY c.SYMBOL, d.FULL_DATE;

-- D.5 Summary statistics by symbol (executive view)
-- Combines multiple metrics in a single query
SELECT c.SYMBOL, c.COMPANY_NAME, c.SECTOR,
       MIN(d.FULL_DATE) AS FIRST_QUOTE,
       MAX(d.FULL_DATE) AS LAST_QUOTE,
       COUNT(*) AS TOTAL_DAYS,
       ROUND(MIN(f.CLOSE_PRICE), 2) AS HISTORICAL_MIN_PRICE,
       ROUND(MAX(f.CLOSE_PRICE), 2) AS HISTORICAL_MAX_PRICE,
       ROUND(AVG(f.CLOSE_PRICE), 2) AS AVG_PRICE,
       ROUND(MEDIAN(f.CLOSE_PRICE), 2) AS MEDIAN_PRICE,
       ROUND(STDDEV(f.CLOSE_PRICE), 2) AS PRICE_STD_DEV,
       ROUND(AVG(f.DAILY_RETURN_PCT), 4) AS AVG_DAILY_RETURN,
       ROUND(STDDEV(f.DAILY_RETURN_PCT), 4) AS DAILY_RETURN_STD_DEV,
       ROUND(AVG(f.VOLATILITY_20), 4) AS AVG_VOLATILITY,
       ROUND(SUM(f.TRADED_VALUE) / 1e9, 2) AS TOTAL_VALUE_BILLIONS
FROM FACT_DAILY_QUOTE f
JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY --AND c.IS_CURRENT = 'Y'
JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
GROUP BY c.SYMBOL, c.COMPANY_NAME, c.SECTOR
ORDER BY c.SECTOR, c.SYMBOL;