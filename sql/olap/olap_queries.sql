-- SECTION A: TIME-SERIES ANALYSIS
-- ============================================================

-- A.1 Cumulative return from the first quote per symbol
-- Uses FIRST_VALUE to anchor the base price at t=0
SELECT c.SYMBOL, c.COMPANY_NAME, d.FULL_DATE, f.CLOSE_PRICE,
       FIRST_VALUE(f.CLOSE_PRICE) OVER (PARTITION BY f.COMPANY_KEY
           ORDER BY f.DATE_KEY ROWS UNBOUNDED PRECEDING) AS BASE_PRICE,
       ROUND((f.CLOSE_PRICE / FIRST_VALUE(f.CLOSE_PRICE) OVER (
           PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
           ROWS UNBOUNDED PRECEDING) - 1) * 100, 2) AS CUMULATIVE_RETURN_PCT
FROM FACT_DAILY_QUOTE f
JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY --AND c.IS_CURRENT = 'Y'
JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
ORDER BY c.SYMBOL, d.FULL_DATE;

SELECT f.SMA_20, c.SYMBOL, d.YEAR_NUM, d.MONTH_NUM
FROM FACT_DAILY_QUOTE f
INNER JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY
INNER JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
WHERE c.SYMBOL = 'JPM' AND d.YEAR_NUM IN (2024, 2025, 2026);

-- A.2 Average monthly closing price with hierarchical ROLLUP
-- Hierarchy: Year > Month > Symbol
-- GROUPING() identifies subtotal/total rows
SELECT GROUPING(d.YEAR_NUM) AS G_YEAR,
       GROUPING(d.MONTH_NUM) AS G_MONTH,
       GROUPING(c.SYMBOL) AS G_SYMBOL,
       NVL(TO_CHAR(d.YEAR_NUM), '(ALL)') AS YEAR,
       NVL(TO_CHAR(d.MONTH_NUM, 'FM00'), '(ALL)') AS MONTH,
       NVL(c.SYMBOL, '(ALL)') AS SYMBOL,
       ROUND(AVG(f.CLOSE_PRICE), 2) AS AVG_CLOSE,
       ROUND(SUM(f.VOLUME) / 1e6, 2) AS VOLUME_MILLIONS
FROM FACT_DAILY_QUOTE f
JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY --AND c.IS_CURRENT = 'Y'
GROUP BY ROLLUP (d.YEAR_NUM, d.MONTH_NUM, c.SYMBOL)
ORDER BY d.YEAR_NUM, d.MONTH_NUM, c.SYMBOL;

-- A.3 Year-over-year variation: annual average price vs. prior year
-- LAG over an annual window per symbol
WITH ANNUAL AS (
    SELECT c.SYMBOL, d.YEAR_NUM,
           ROUND(AVG(f.CLOSE_PRICE), 2) AS AVG_PRICE
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY --AND c.IS_CURRENT = 'Y'
    GROUP BY c.SYMBOL, d.YEAR_NUM
)
SELECT SYMBOL, YEAR_NUM, AVG_PRICE,
       LAG(AVG_PRICE) OVER (PARTITION BY SYMBOL ORDER BY YEAR_NUM) AS PRIOR_YEAR_PRICE,
       ROUND((AVG_PRICE / NULLIF(LAG(AVG_PRICE) OVER (
           PARTITION BY SYMBOL ORDER BY YEAR_NUM), 0) - 1) * 100, 2) AS YOY_VARIATION_PCT
FROM ANNUAL
ORDER BY SYMBOL, YEAR_NUM;

-- A.4 Best and worst return quarter per symbol
-- RANK() within each company
WITH QUARTERLY AS (
    SELECT c.SYMBOL, d.YEAR_NUM, d.QUARTER_NUM,
           ROUND(AVG(f.DAILY_RETURN_PCT), 4) AS AVG_QUARTER_RETURN
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    WHERE f.DAILY_RETURN_PCT IS NOT NULL
    GROUP BY c.SYMBOL, d.YEAR_NUM, d.QUARTER_NUM
),
RANKED AS (
    SELECT SYMBOL, YEAR_NUM, QUARTER_NUM, AVG_QUARTER_RETURN,
           RANK() OVER (PARTITION BY SYMBOL ORDER BY AVG_QUARTER_RETURN DESC) AS BEST_RANK,
           RANK() OVER (PARTITION BY SYMBOL ORDER BY AVG_QUARTER_RETURN ASC) AS WORST_RANK
    FROM QUARTERLY
)
SELECT SYMBOL, YEAR_NUM || '-Q' || QUARTER_NUM AS QUARTER,
       AVG_QUARTER_RETURN,
       CASE WHEN BEST_RANK = 1 THEN 'BEST' END AS IS_BEST,
       CASE WHEN WORST_RANK = 1 THEN 'WORST' END AS IS_WORST
FROM RANKED
WHERE BEST_RANK = 1 OR WORST_RANK = 1
ORDER BY SYMBOL, YEAR_NUM;

-- A.5 52-week high and low (252-business-day window)
-- Identifies when a stock reaches its annual high/low
SELECT c.SYMBOL, d.FULL_DATE, f.CLOSE_PRICE,
       MAX(f.CLOSE_PRICE) OVER (PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
           ROWS BETWEEN 251 PRECEDING AND CURRENT ROW) AS HIGH_52W,
       MIN(f.CLOSE_PRICE) OVER (PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
           ROWS BETWEEN 251 PRECEDING AND CURRENT ROW) AS LOW_52W,
       CASE WHEN f.CLOSE_PRICE = MAX(f.CLOSE_PRICE) OVER (
           PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
           ROWS BETWEEN 251 PRECEDING AND CURRENT ROW)
           THEN 'HIGH_52W' END AS HITS_HIGH,
       CASE WHEN f.CLOSE_PRICE = MIN(f.CLOSE_PRICE) OVER (
           PARTITION BY f.COMPANY_KEY ORDER BY f.DATE_KEY
           ROWS BETWEEN 251 PRECEDING AND CURRENT ROW)
           THEN 'LOW_52W' END AS HITS_LOW
FROM FACT_DAILY_QUOTE f
JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
ORDER BY c.SYMBOL, d.FULL_DATE;

-- A.6 Rolling volatility by quarter: VOLATILITY_20 average
-- Identifies high-/low-volatility regimes
SELECT c.SYMBOL, d.YEAR_NUM, d.QUARTER_NUM,
       ROUND(AVG(f.VOLATILITY_20), 4) AS AVG_QUARTER_VOLATILITY,
       ROUND(MAX(f.VOLATILITY_20), 4) AS MAX_QUARTER_VOLATILITY,
       RANK() OVER (PARTITION BY c.SYMBOL ORDER BY AVG(f.VOLATILITY_20) DESC) AS MOST_VOLATILE_RANK
FROM FACT_DAILY_QUOTE f
INNER JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
INNER JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
WHERE 1 = 1 AND f.VOLATILITY_20 IS NOT NULL
GROUP BY c.SYMBOL, d.YEAR_NUM, d.QUARTER_NUM
ORDER BY c.SYMBOL, d.YEAR_NUM, d.QUARTER_NUM;

-- ============================================================
-- SECTION B: PATTERN MATCHING (MATCH_RECOGNIZE)
-- ============================================================

-- B.1 Detect bullish streak: 3 or more consecutive days
-- with an increasing CLOSE_PRICE (each day > previous day)
SELECT SYMBOL, START_DATE, END_DATE, STREAK_DAYS, START_PRICE, END_PRICE,
       ROUND((END_PRICE / START_PRICE - 1) * 100, 2) AS STREAK_GAIN_PCT
FROM (
    SELECT c.SYMBOL, d.FULL_DATE AS TRADE_DATE, f.CLOSE_PRICE
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
)
MATCH_RECOGNIZE (
    PARTITION BY SYMBOL
    ORDER BY TRADE_DATE
    MEASURES FIRST(TRADE_DATE) AS START_DATE,
             LAST(TRADE_DATE) AS END_DATE,
             COUNT(*) AS STREAK_DAYS,
             FIRST(CLOSE_PRICE) AS START_PRICE,
             LAST(CLOSE_PRICE) AS END_PRICE
    ONE ROW PER MATCH
    AFTER MATCH SKIP TO NEXT ROW
    PATTERN (UP{3,})
    DEFINE UP AS CLOSE_PRICE > PREV(CLOSE_PRICE)
)
WHERE STREAK_DAYS >= 3
ORDER BY SYMBOL, START_DATE;

-- B.2 Detect bearish streak: 3 or more consecutive days
-- with a decreasing CLOSE_PRICE
SELECT SYMBOL, START_DATE, END_DATE, STREAK_DAYS, START_PRICE, END_PRICE,
       ROUND((END_PRICE / START_PRICE - 1) * 100, 2) AS STREAK_LOSS_PCT
FROM (
    SELECT c.SYMBOL, d.FULL_DATE AS TRADE_DATE, f.CLOSE_PRICE
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
)
MATCH_RECOGNIZE (
    PARTITION BY SYMBOL
    ORDER BY TRADE_DATE
    MEASURES FIRST(TRADE_DATE) AS START_DATE,
             LAST(TRADE_DATE) AS END_DATE,
             COUNT(*) AS STREAK_DAYS,
             FIRST(CLOSE_PRICE) AS START_PRICE,
             LAST(CLOSE_PRICE) AS END_PRICE
    ONE ROW PER MATCH
    AFTER MATCH SKIP TO NEXT ROW
    PATTERN (DOWN{3,})
    DEFINE DOWN AS CLOSE_PRICE < PREV(CLOSE_PRICE)
)
WHERE STREAK_DAYS >= 3
ORDER BY SYMBOL, START_DATE;

-- B.3 V-shaped recovery pattern: bearish streak followed by bullish streak
-- At least 3 declining days and at least 3 rising days
SELECT SYMBOL, DECLINE_START, BOTTOM, REBOUND_END,
       PREVIOUS_PEAK_PRICE, BOTTOM_PRICE, REBOUND_PRICE,
       ROUND((BOTTOM_PRICE / PREVIOUS_PEAK_PRICE - 1) * 100, 2) AS DECLINE_PCT,
       ROUND((REBOUND_PRICE / BOTTOM_PRICE - 1) * 100, 2) AS REBOUND_PCT
FROM (
    SELECT c.SYMBOL, d.FULL_DATE AS TRADE_DATE, f.CLOSE_PRICE
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
)
MATCH_RECOGNIZE (
    PARTITION BY SYMBOL
    ORDER BY TRADE_DATE
    MEASURES FIRST(DOWN.TRADE_DATE) AS DECLINE_START,
             LAST(DOWN.TRADE_DATE) AS BOTTOM,
             LAST(UP.TRADE_DATE) AS REBOUND_END,
             FIRST(DOWN.CLOSE_PRICE) AS PREVIOUS_PEAK_PRICE,
             LAST(DOWN.CLOSE_PRICE) AS BOTTOM_PRICE,
             LAST(UP.CLOSE_PRICE) AS REBOUND_PRICE
    ONE ROW PER MATCH
    AFTER MATCH SKIP TO NEXT ROW
    PATTERN (DOWN{3,} UP{3,})
    DEFINE DOWN AS CLOSE_PRICE < PREV(CLOSE_PRICE),
           UP AS CLOSE_PRICE > PREV(CLOSE_PRICE)
)
ORDER BY SYMBOL, DECLINE_START;

-- B.4 Golden Cross signal: first day when SMA_20 exceeds EMA_20
-- (positive crossover → bullish technical signal)
SELECT SYMBOL, CROSS_DATE, SMA_AT_CROSS, EMA_AT_CROSS, CLOSE_AT_CROSS
FROM (
    SELECT c.SYMBOL, d.FULL_DATE AS TRADE_DATE,
           f.SMA_20, f.EMA_20, f.CLOSE_PRICE
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
    WHERE f.SMA_20 IS NOT NULL AND f.EMA_20 IS NOT NULL
)
MATCH_RECOGNIZE (
    PARTITION BY SYMBOL
    ORDER BY TRADE_DATE
    MEASURES FIRST(CROSS.TRADE_DATE) AS CROSS_DATE,
             FIRST(CROSS.SMA_20) AS SMA_AT_CROSS,
             FIRST(CROSS.EMA_20) AS EMA_AT_CROSS,
             FIRST(CROSS.CLOSE_PRICE) AS CLOSE_AT_CROSS
    ONE ROW PER MATCH
    AFTER MATCH SKIP TO NEXT ROW
    PATTERN (BELOW CROSS)
    DEFINE BELOW AS SMA_20 <= EMA_20,
           CROSS AS SMA_20 > EMA_20
)
ORDER BY SYMBOL, CROSS_DATE;

-- B.5 Death Cross signal: first day when SMA_20 falls below EMA_20
-- (negative crossover → bearish technical signal)
SELECT SYMBOL, CROSS_DATE, SMA_AT_CROSS, EMA_AT_CROSS, CLOSE_AT_CROSS
FROM (
    SELECT c.SYMBOL, d.FULL_DATE AS TRADE_DATE,
           f.SMA_20, f.EMA_20, f.CLOSE_PRICE
    FROM FACT_DAILY_QUOTE f
    JOIN DIM_COMPANY c ON c.COMPANY_KEY = f.COMPANY_KEY AND c.IS_CURRENT = 'Y'
    JOIN DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
    WHERE f.SMA_20 IS NOT NULL AND f.EMA_20 IS NOT NULL
)
MATCH_RECOGNIZE (
    PARTITION BY SYMBOL
    ORDER BY TRADE_DATE
    MEASURES FIRST(CROSS.TRADE_DATE) AS CROSS_DATE,
             FIRST(CROSS.SMA_20) AS SMA_AT_CROSS,
             FIRST(CROSS.EMA_20) AS EMA_AT_CROSS,
             FIRST(CROSS.CLOSE_PRICE) AS CLOSE_AT_CROSS
    ONE ROW PER MATCH
    AFTER MATCH SKIP TO NEXT ROW
    PATTERN (ABOVE CROSS)
    DEFINE ABOVE AS SMA_20 >= EMA_20,
           CROSS AS SMA_20 < EMA_20
)
ORDER BY SYMBOL, CROSS_DATE;

